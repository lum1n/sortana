#!/usr/bin/env python3
"""Regenerate src/catalog.rs from presets/lineups.toml and the models.dev catalogue.

    python3 scripts/update-catalog.py                # download https://models.dev/api.json
    python3 scripts/update-catalog.py path/api.json  # use a saved copy

For every host (models.dev provider) it records the host's model id for each
model in a lineup, matched by models.dev's `canonical_model_id`, or by an id
equal to the model name (or `maker/name`) where models.dev has no canonical
link. Fails when a
lineup names a model that models.dev does not know or lists only as deprecated.
Free promotional variants (`-free`, `:free`) are skipped.
"""

import datetime
import json
import subprocess
import sys
import tomllib
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINEUPS = ROOT / "presets" / "lineups.toml"
OUT = ROOT / "src" / "catalog.rs"
URL = "https://models.dev/api.json"


def rust_str(s: str) -> str:
    if not s.isprintable() or not s.isascii():
        raise SystemExit(f"refusing non-ASCII or unprintable id: {s!r}")
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def pick_id(ids: list[str], model: str) -> str:
    """Prefer the id equal to the bare model name, then the shortest (avoids
    region-prefixed variants such as `jp.anthropic...` on Bedrock)."""
    if model in ids:
        return model
    return min(ids, key=lambda i: (len(i), i))


def main() -> None:
    if len(sys.argv) > 1:
        catalogue = json.loads(Path(sys.argv[1]).read_text())
    else:
        req = urllib.request.Request(URL, headers={"User-Agent": "sortana-update-catalog"})
        with urllib.request.urlopen(req, timeout=60) as resp:
            catalogue = json.load(resp)
    lineups = tomllib.loads(LINEUPS.read_text())

    wanted = {f"{maker}/{m}" for maker, l in lineups.items() for m in l["models"]}
    # Fallback for host models without a usable canonical link.
    by_id = {}
    for cid in wanted:
        by_id[cid] = cid
        by_id.setdefault(cid.split("/", 1)[1], cid)

    # host -> canonical -> candidate host ids (non-deprecated only)
    served: dict[str, dict[str, list[str]]] = {}
    known: set[str] = set()
    for host, provider in catalogue.items():
        for mid, m in provider.get("models", {}).items():
            cid = m.get("canonical_model_id")
            if cid not in wanted:
                cid = by_id.get(mid)
            if cid is None:
                continue
            known.add(cid)
            # Skip retired models and temporary free promotions (rate-limited,
            # and they come and go between catalogue snapshots).
            if m.get("status") == "deprecated" or mid.endswith(("-free", ":free")):
                continue
            served.setdefault(host, {}).setdefault(cid, []).append(mid)

    live = {cid for per_host in served.values() for cid in per_host}
    errors = [f"{cid}: not in models.dev" for cid in sorted(wanted - known)]
    errors += [f"{cid}: deprecated on every host" for cid in sorted(known - live)]
    if errors:
        raise SystemExit("lineup errors:\n  " + "\n  ".join(errors))

    # Explicit native ids override what the maker's own host lists.
    for maker, l in lineups.items():
        if len(l["models"]) != 4 or len(l.get("native", l["models"])) != 4:
            raise SystemExit(f"{maker}: models and native need 4 entries each")
        if "native" in l:
            if maker not in catalogue:
                raise SystemExit(f"{maker}: native ids given, but models.dev has no {maker} host")
            for m, n in zip(l["models"], l["native"]):
                served.setdefault(maker, {})[f"{maker}/{m}"] = [n]

    rows = sorted(
        (host, cid, pick_id(ids, cid.split("/", 1)[1]))
        for host, per_host in served.items()
        for cid, ids in per_host.items()
    )
    hosts = sorted(served)

    out = [
        "// @generated by scripts/update-catalog.py. Do not edit by hand.",
        "// Edit presets/lineups.toml and re-run the script instead.",
        "",
        "use crate::models::{Host, Lineup};",
        "",
        "/// Date the catalogue was generated from models.dev.",
        f"pub const CATALOG_DATE: &str = {rust_str(datetime.date.today().isoformat())};",
        "",
        "pub(crate) static LINEUPS: &[Lineup] = &[",
    ]
    for maker, l in lineups.items():
        canonical = [f"{maker}/{m}" for m in l["models"]]
        native = []
        for c, m in zip(canonical, l["models"]):
            if c in served.get(maker, {}):
                native.append(pick_id(served[maker][c], m))
            else:
                native.append(m)
                if maker in catalogue:
                    print(f"warning: {c} not found on {maker}'s own API; add `native` ids", file=sys.stderr)
        out += [
            "    Lineup {",
            f"        id: {rust_str(maker)},",
            f"        name: {rust_str(l['name'])},",
            f"        canonical: [{', '.join(map(rust_str, canonical))}],",
            f"        native: [{', '.join(map(rust_str, native))}],",
            "    },",
        ]
    out += ["];", "", "/// Sorted by id.", "pub(crate) static HOSTS: &[Host] = &["]
    for h in hosts:
        out.append(f"    Host {{ id: {rust_str(h)}, name: {rust_str(catalogue[h].get('name', h))} }},")
    out += ["];", "", "/// (host, canonical id, host model id), sorted.",
            "pub(crate) static HOST_MODELS: &[(&str, &str, &str)] = &["]
    for host, cid, mid in rows:
        out.append(f"    ({rust_str(host)}, {rust_str(cid)}, {rust_str(mid)}),")
    out += ["];", ""]

    OUT.write_text("\n".join(out))
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(lineups)} lineups, {len(hosts)} hosts, {len(rows)} host models")


if __name__ == "__main__":
    main()
